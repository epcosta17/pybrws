#!/usr/bin/env python3
"""Work out which protection a host sits behind, from its own answer.

Guessing which sites use which vendor from memory is how a results table ends
up measuring something other than what it claims. Every vendor here leaves
something in the response -- a header, a cookie name, or a phrase on its
block page -- so the list of targets can be probed rather than asserted.

    python tools/detect_waf.py
    python tools/detect_waf.py --vendor imperva --urls urls.txt

Detection runs on whatever came back, block page included: a 403 from
Incapsula is still an Incapsula fingerprint, and is in fact the interesting
case.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from pybrws.client import get  # noqa: E402

# Each vendor: header names, Set-Cookie name prefixes, and body phrases.
# Kept narrow on purpose -- a marker that also matches something else makes
# the table wrong in the direction that is hardest to notice.
SIGNATURES: dict[str, dict[str, tuple[str, ...]]] = {
    "imperva": {
        "headers": ("x-iinfo", "x-cdn"),
        "header_values": ("incapsula", "imperva"),
        "cookies": ("visid_incap_", "incap_ses_", "nlbi_"),
        "body": ("incapsula incident id", "powered by imperva",
                 "request unsuccessful"),
    },
    "cloudflare": {
        "headers": ("cf-ray", "cf-cache-status"),
        "header_values": ("cloudflare",),
        "cookies": ("__cf_bm", "cf_clearance", "__cfruid"),
        "body": ("attention required", "cloudflare ray id",
                 "checking your browser"),
    },
    "akamai": {
        "headers": ("x-akamai-transformed", "akamai-grn"),
        "header_values": ("akamaighost",),
        "cookies": ("_abck", "bm_sz", "ak_bmsc", "bm_sv"),
        "body": ("reference #", "access denied"),
    },
    "datadome": {
        "headers": ("x-datadome", "x-dd-b"),
        "header_values": ("datadome",),
        "cookies": ("datadome",),
        "body": ("geo.captcha-delivery.com", "datadome"),
    },
    "perimeterx": {
        "headers": ("x-px",),
        "header_values": ("perimeterx",),
        "cookies": ("_px", "_pxhd", "_pxvid"),
        "body": ("px-captcha", "perimeterx"),
    },
    "cloudfront": {
        "headers": ("x-amz-cf-id", "x-amz-cf-pop"),
        "header_values": ("cloudfront",),
        "cookies": (),
        "body": ("generated by cloudfront",),
    },
    "fastly": {
        "headers": ("x-served-by", "x-fastly-request-id"),
        "header_values": ("fastly",),
        "cookies": (),
        "body": (),
    },
    "f5": {
        "headers": ("x-cnection",),
        "header_values": ("big-ip", "bigip"),
        "cookies": ("ts01", "bigipserver"),
        "body": ("the requested url was rejected",),
    },
}


def detect(response) -> list[str]:
    """Every vendor whose markers appear in this response."""
    header_names = {name.lower() for name, _ in response.headers}
    header_blob = " ".join(
        "%s: %s" % (name.lower(), value.lower())
        for name, value in response.headers
    )
    cookie_names = " ".join(
        value.split("=", 1)[0].strip().lower()
        for name, value in response.headers
        if name.lower() == "set-cookie"
    )
    try:
        body = response.body[:20000].decode("utf-8", "replace").lower()
    except Exception:
        body = ""

    found = []
    for vendor, marks in SIGNATURES.items():
        hit = None
        for header in marks["headers"]:
            if header in header_names:
                hit = "header " + header
                break
        if hit is None:
            for value in marks["header_values"]:
                if value in header_blob:
                    hit = "header value " + value
                    break
        if hit is None:
            for cookie in marks["cookies"]:
                if cookie in cookie_names:
                    hit = "cookie " + cookie
                    break
        if hit is None:
            for phrase in marks["body"]:
                if phrase in body:
                    hit = "body " + repr(phrase)
                    break
        if hit is not None:
            found.append("%s (%s)" % (vendor, hit))
    return found


