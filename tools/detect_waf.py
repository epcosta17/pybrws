def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--urls", type=Path,
                        help="a file of URLs, one per line")
    parser.add_argument("--vendor",
                        help="only print hosts where this vendor was found")
    parser.add_argument("--timeout", type=float, default=20.0)
    args = parser.parse_args()

    urls = (CANDIDATES if args.urls is None
            else [line.strip() for line in
                  args.urls.read_text(encoding="utf-8").splitlines()
                  if line.strip() and not line.startswith("#")])

    for url in urls:
        try:
            response = get(url, timeout=args.timeout)
            vendors = detect(response)
            if args.vendor and not any(v.startswith(args.vendor)
                                       for v in vendors):
                continue
            print("  %-44s %3d  %s" % (url[:44], response.status,
                                       ", ".join(vendors) or "nothing matched"))
        except Exception as exc:
            if args.vendor:
                continue
            print("  %-44s  -   %s: %s"
                  % (url[:44], type(exc).__name__, str(exc)[:50]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
